/// 应用内多语言：简体中文 / 繁體中文 / English / 日本語 / 한국어。
/// 由设置页「语言」选项驱动，全局函数 [t] 取当前语言的文案。
library;

import 'dart:io';

import 'package:flutter/material.dart';

enum AppLanguage {
  system('system'),
  zhCN('zh-CN'),
  zhTW('zh-TW'),
  en('en'),
  ja('ja'),
  ko('ko');

  const AppLanguage(this.id);
  final String id;

  static AppLanguage fromId(String? id) => switch (id) {
        'zh-TW' => AppLanguage.zhTW,
        'en' => AppLanguage.en,
        'ja' => AppLanguage.ja,
        'ko' => AppLanguage.ko,
        _ => AppLanguage.zhCN,
      };
}

/// 当前界面语言（由 SettingsService 在启动时与切换时设置）。
AppLanguage _current = AppLanguage.zhCN;
AppLanguage get currentLanguage => _current;
void setCurrentLanguage(AppLanguage lang) => _current = lang;

/// 系统语言对应的默认语言（跟随系统模式）。
AppLanguage systemLanguage() {
  final tag = Platform.localeName.toLowerCase();
  if (tag.startsWith('zh')) {
    return tag.contains('tw') || tag.contains('hk') || tag.contains('hant')
        ? AppLanguage.zhTW
        : AppLanguage.zhCN;
  }
  if (tag.startsWith('ja')) return AppLanguage.ja;
  if (tag.startsWith('ko')) return AppLanguage.ko;
  return AppLanguage.en;
}

/// 取当前语言文案；参数用 {n} 占位符替换。
String t(String key, [Map<String, Object>? args]) {
  var text = _strings[_current]?[key] ?? _strings[AppLanguage.zhCN]![key]!;
  if (args != null) {
    for (final entry in args.entries) {
      text = text.replaceAll('{${entry.key}}', entry.value.toString());
    }
  }
  return text;
}

